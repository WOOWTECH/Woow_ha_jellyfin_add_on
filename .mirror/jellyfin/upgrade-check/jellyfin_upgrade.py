"""The upgrade test's data check of Jellyfin (pipeline release-gating/176).

The Store's upgrade test (Woow_HA_App_Store .addon-sync/upgrade_runtime.py)
runs `seed` on the comparison target and `verify` on the new version, on the
same data directories, from the mock Supervisor's container (python3 and
busybox only). Both go through Jellyfin's own REST API on port 8096 of
ADDON_HOST (the add-on's NGINX in front of Jellyfin, the port the Jellyfin
apps and the Home Assistant integration use), never its database:

seed     Jellyfin is up (/System/Info/Public) on a fresh /config, and its
         startup wizard is not done yet. The wizard is completed through the
         /Startup API (an administrator with a random password), the
         administrator logs in, a second user (with its own password) and a
         movie library pointing at an empty folder in /media are created and
         read back.
verify   Jellyfin is up on the new version: /System/Info/Public answers (its
         own database migrations run before it serves the API), reports the
         same server id, a version not older than before and the wizard still
         done. The administrator and the second user still log in with their
         passwords and keep their ids, the user is still listed, the library
         is still there with the same id, type and folder, and creating (then
         deleting) a user works on the migrated database.

The passwords are generated by seed and kept only in HOOK_STATE_DIR (never
mounted in the add-on). Each check goes to $REPORT_DIR/<hook>.json; the hook
exits 1 when one fails. Standard library only (the hooks run on
python:3.12-alpine).
"""
from __future__ import annotations

import json
import os
import re
import secrets
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

API_PORT = 8096
READY_TIMEOUT = 420
STATE_FILE = "jellyfin-seed.json"
CLIENT = 'Client="woow-upgrade-check", Device="upgrade-test", DeviceId="woow-upgrade-check", Version="1.0"'


def hook_timeout() -> int:
    """The Store's hook_timeout: this directory's settings.yaml if it sets one, else the Store's default 600 s.

    Only a top-level `hook_timeout: <seconds>` line is read (the hooks have no YAML library).
    """
    try:
        with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "settings.yaml"), encoding="utf-8") as f:
            for line in f:
                match = re.match(r"""hook_timeout\s*:\s*["']?(\d+)["']?\s*(#.*)?$""", line.rstrip())
                if match:
                    return int(match.group(1))
    except OSError:
        pass
    return 600


HOOK_TIMEOUT = hook_timeout()
# The whole hook ends this far inside hook_timeout, so it always writes its
# report before the Store kills it.
HOOK_BUDGET = max(HOOK_TIMEOUT - 120, HOOK_TIMEOUT // 2)
DEADLINE = time.monotonic() + HOOK_BUDGET


def time_left(cap: float) -> float:
    """At most `cap` seconds, and no more than the hook has left; fails the check once the budget is used up."""
    left = DEADLINE - time.monotonic()
    if left < 1:
        raise AssertionError(f"the hook's {HOOK_BUDGET} s budget is used up (hook_timeout is {HOOK_TIMEOUT} s)")
    return min(cap, left)


def norm_id(value: object) -> str:
    """A Jellyfin id (a GUID, written with or without dashes) in one form."""
    return str(value or "").replace("-", "").lower()


def version_tuple(text: object) -> tuple[int, ...]:
    return tuple(int(n) for n in re.findall(r"\d+", str(text))[:4])


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *args, **kwargs):  # noqa: ANN002, ANN003 - urllib's signature
        return None


class Client:
    """Jellyfin's REST API, anonymous or with a user's access token."""

    def __init__(self) -> None:
        self.api = f"http://{os.environ['ADDON_HOST']}:{API_PORT}"
        self.token = ""
        # No redirects: an answer that redirects is reported as it is.
        self.opener = urllib.request.build_opener(NoRedirect)

    def request(self, method: str, path: str, body: object | None = None, token: str | None = None,
                timeout: float = 30) -> tuple[int, bytes]:
        token = self.token if token is None else token
        auth = f"MediaBrowser {CLIENT}" + (f', Token="{token}"' if token else "")
        headers = {"Accept": "application/json", "Authorization": auth}
        data = None
        if body is not None:
            data = json.dumps(body).encode()
            headers["Content-Type"] = "application/json"
        req = urllib.request.Request(self.api + path, data=data, method=method, headers=headers)
        timeout = time_left(timeout)
        try:
            with self.opener.open(req, timeout=timeout) as response:
                return response.status, response.read()
        except urllib.error.HTTPError as error:
            return error.code, error.read()
        except (urllib.error.URLError, OSError) as error:
            return 0, str(error).encode()

    def call(self, method: str, path: str, body: object | None = None, want: tuple[int, ...] = (200,),
             token: str | None = None) -> object:
        code, raw = self.request(method, path, body, token)
        if code not in want:
            raise AssertionError(f"{method} {path} -> {code}: {raw[:300].decode(errors='replace')}")
        if not raw.strip():
            return {}
        try:
            return json.loads(raw)
        except json.JSONDecodeError as error:
            raise AssertionError(f"{method} {path} is not JSON: {raw[:200].decode(errors='replace')}") from error

    def wait_public_info(self) -> dict:
        """/System/Info/Public until it answers 200 with a version (Jellyfin has opened and migrated its database)."""
        deadline = time.monotonic() + time_left(READY_TIMEOUT)
        while True:
            code, raw = self.request("GET", "/System/Info/Public", token="", timeout=10)
            if code == 200:
                try:
                    info = json.loads(raw)
                except json.JSONDecodeError:
                    info = None
                if isinstance(info, dict) and info.get("Version") and info.get("Id"):
                    return info
            if time.monotonic() > deadline - 3:
                raise AssertionError(f"no /System/Info/Public within the wait: last {code} {raw[:200].decode(errors='replace')}")
            time.sleep(3)

    def login(self, name: str, password: str) -> dict:
        """POST /Users/AuthenticateByName; the session's token becomes this client's token. The logged-in user."""
        data = self.call("POST", "/Users/AuthenticateByName", {"Username": name, "Pw": password}, token="")
        assert isinstance(data, dict) and data.get("AccessToken"), f"login of {name} gave no access token: {sorted(data) if isinstance(data, dict) else data!r}"
        user = data.get("User") or {}
        assert user.get("Name") == name and user.get("Id"), f"login of {name} returned user {user.get('Name')!r}"
        self.token = data["AccessToken"]
        return user

    def users(self) -> list[dict]:
        users = self.call("GET", "/Users")
        assert isinstance(users, list), f"GET /Users is not a list: {users!r}"[:300]
        return users

    def libraries(self) -> list[dict]:
        folders = self.call("GET", "/Library/VirtualFolders")
        assert isinstance(folders, list), f"GET /Library/VirtualFolders is not a list: {folders!r}"[:300]
        return folders


class Checks:
    """Each check runs even when an earlier one failed, unless it needs what that one made."""

    def __init__(self) -> None:
        self.items: list[dict[str, str]] = []

    def run(self, name: str, check, needs: bool = True) -> object:
        if not needs:
            self.items.append({"name": name, "result": "skip", "detail": "an earlier check it needs failed"})
            return None
        try:
            value = check()
        except Exception as error:  # noqa: BLE001 - every failure is a failed check with its reason
            self.items.append({"name": name, "result": "fail", "detail": f"{type(error).__name__}: {error}"[:500]})
            print(f"FAIL {name}: {error}", flush=True)
            return None
        detail = value if isinstance(value, str) else "ok"
        self.items.append({"name": name, "result": "pass", "detail": detail})
        print(f"pass {name}: {detail}", flush=True)
        return value if value is not None else True

    def finish(self, hook: str) -> int:
        with open(os.path.join(os.environ["REPORT_DIR"], f"{hook}.json"), "w", encoding="utf-8") as f:
            json.dump({"checks": self.items}, f, indent=1)
        return 1 if any(c["result"] != "pass" for c in self.items) else 0


def state_path() -> str:
    return os.path.join(os.environ["HOOK_STATE_DIR"], STATE_FILE)


def library_fields(folder: dict) -> dict[str, object]:
    """What verify compares of a library (virtual folder)."""
    return {"name": folder.get("Name"), "id": norm_id(folder.get("ItemId")),
            "type": str(folder.get("CollectionType") or "").lower(), "locations": sorted(folder.get("Locations") or [])}


def seed() -> int:
    checks, state = Checks(), {}
    jf = Client()
    tag = secrets.token_hex(4)
    admin = {"name": f"woow-admin-{tag}", "password": secrets.token_urlsafe(18)}
    viewer = {"name": f"woow-viewer-{tag}", "password": secrets.token_urlsafe(18)}
    folder = f"woow-upgrade-{tag}"
    library = {"name": f"Woow upgrade {tag}", "path": f"/media/{folder}"}

    def up() -> str:
        info = jf.wait_public_info()
        assert info.get("StartupWizardCompleted") is False, \
            f"the startup wizard is already done (StartupWizardCompleted is {info.get('StartupWizardCompleted')!r}) on a fresh /config"
        state.update(version=str(info["Version"]), server_id=norm_id(info["Id"]))
        return f"Jellyfin {info['Version']} (server id {state['server_id']}), startup wizard not done yet"
    is_up = checks.run("Jellyfin up (/System/Info/Public)", up)

    def wizard() -> str:
        jf.call("POST", "/Startup/Configuration", {"UICulture": "en-US", "MetadataCountryCode": "US",
                                                   "PreferredMetadataLanguage": "en"}, want=(200, 204), token="")
        jf.call("GET", "/Startup/User", token="")  # Jellyfin makes its first user here when there is none yet
        jf.call("POST", "/Startup/User", {"Name": admin["name"], "Password": admin["password"]}, want=(200, 204), token="")
        jf.call("POST", "/Startup/RemoteAccess", {"EnableRemoteAccess": True, "EnableAutomaticPortMapping": False},
                want=(200, 204), token="")
        jf.call("POST", "/Startup/Complete", want=(200, 204), token="")
        info = jf.wait_public_info()
        assert info.get("StartupWizardCompleted") is True, f"StartupWizardCompleted is {info.get('StartupWizardCompleted')!r} after /Startup/Complete"
        return f"wizard completed through /Startup with administrator {admin['name']}"
    done = checks.run("startup wizard completed", wizard, bool(is_up))

    def admin_login() -> str:
        user = jf.login(admin["name"], admin["password"])
        assert (user.get("Policy") or {}).get("IsAdministrator") is True, f"{admin['name']} is not an administrator"
        admin["id"] = norm_id(user["Id"])
        state["admin"] = admin
        return f"administrator {admin['name']} (id {admin['id']}) logs in"
    logged_in = checks.run("administrator logs in", admin_login, bool(done))

    def make_user() -> str:
        made = jf.call("POST", "/Users/New", {"Name": viewer["name"], "Password": viewer["password"]})
        assert isinstance(made, dict) and made.get("Name") == viewer["name"] and made.get("Id"), f"created user is {made!r}"[:300]
        viewer["id"] = norm_id(made["Id"])
        listed = [u for u in jf.users() if u.get("Name") == viewer["name"]]
        assert len(listed) == 1 and norm_id(listed[0].get("Id")) == viewer["id"], f"GET /Users lists {listed!r}"[:300]
        own = Client().login(viewer["name"], viewer["password"])
        assert norm_id(own.get("Id")) == viewer["id"], f"{viewer['name']} logs in as id {own.get('Id')}"
        state["viewer"] = viewer
        return f"user {viewer['name']} (id {viewer['id']}) created, listed and logs in with its password"
    checks.run("user created", make_user, bool(logged_in))

    def make_library() -> str:
        media = os.environ["DATA_DIR_MEDIA"]
        os.makedirs(os.path.join(media, folder), exist_ok=True)
        query = urllib.parse.urlencode({"name": library["name"], "collectionType": "movies",
                                        "paths": library["path"], "refreshLibrary": "false"})
        jf.call("POST", f"/Library/VirtualFolders?{query}", {"LibraryOptions": {}}, want=(200, 204))
        listed = [f for f in jf.libraries() if f.get("Name") == library["name"]]
        assert len(listed) == 1, f"GET /Library/VirtualFolders lists {len(listed)} libraries named {library['name']}"
        fields = library_fields(listed[0])
        assert fields["type"] == "movies" and fields["locations"] == [library["path"]] and fields["id"], f"listed library is {fields}"
        state["library"] = fields
        return f"movie library {library['name']} (id {fields['id']}) on {library['path']} created and listed"
    checks.run("library created", make_library, bool(logged_in))

    with open(state_path(), "w", encoding="utf-8") as f:
        json.dump(state, f)
    return checks.finish("seed")


def verify() -> int:
    checks = Checks()
    jf = Client()

    def read_state() -> dict[str, object]:
        try:
            with open(state_path(), encoding="utf-8") as f:
                loaded = json.load(f)
        except (OSError, ValueError) as error:
            raise AssertionError(f"seed state {state_path()} unreadable (did seed run?): {error}") from error
        assert isinstance(loaded, dict) and all(loaded.get(k) for k in ("admin", "viewer", "library", "server_id")), \
            f"seed state incomplete: {sorted(loaded) if isinstance(loaded, dict) else loaded!r}"
        return loaded
    state = checks.run("seed state readable", read_state)
    seeded = state is not None

    def up() -> str:
        info = jf.wait_public_info()
        if not seeded:
            return f"Jellyfin {info['Version']}"
        assert norm_id(info["Id"]) == state["server_id"], f"server id is {norm_id(info['Id'])}, {state['server_id']} before the upgrade"
        assert info.get("StartupWizardCompleted") is True, f"StartupWizardCompleted is {info.get('StartupWizardCompleted')!r}: the wizard would start again"
        assert version_tuple(info["Version"]) >= version_tuple(state["version"]), \
            f"Jellyfin {info['Version']} is older than {state['version']} before the upgrade"
        return f"Jellyfin {state['version']} -> {info['Version']}, same server id, wizard still done"
    is_up = checks.run("Jellyfin up on the new version (migrations finished)", up)

    def admin_login() -> str:
        want = state["admin"]
        user = jf.login(want["name"], want["password"])
        assert norm_id(user["Id"]) == want["id"], f"{want['name']} has id {norm_id(user['Id'])}, {want['id']} before"
        assert (user.get("Policy") or {}).get("IsAdministrator") is True, f"{want['name']} is no longer an administrator"
        return f"administrator {want['name']} (id {want['id']}) logs in with its password"
    logged_in = checks.run("administrator still logs in", admin_login, bool(is_up) and seeded)

    def user_kept() -> str:
        want = state["viewer"]
        listed = [u for u in jf.users() if u.get("Name") == want["name"]]
        assert len(listed) == 1, f"{len(listed)} users named {want['name']}"
        assert norm_id(listed[0].get("Id")) == want["id"], f"user {want['name']} has id {listed[0].get('Id')}, {want['id']} before"
        own = Client().login(want["name"], want["password"])
        assert norm_id(own.get("Id")) == want["id"], f"{want['name']} logs in as id {own.get('Id')}"
        return f"user {want['name']} (id {want['id']}) listed and logs in with its password"
    checks.run("user still exists", user_kept, bool(logged_in))

    def library_kept() -> str:
        want = state["library"]
        listed = [f for f in jf.libraries() if f.get("Name") == want["name"]]
        assert len(listed) == 1, f"{len(listed)} libraries named {want['name']}"
        got = library_fields(listed[0])
        for field in ("id", "type", "locations"):
            assert got[field] == want[field], f"{field} is {got[field]!r}, {want[field]!r} before the upgrade"
        return f"library {want['name']} (id {want['id']}, {want['type']}) on {', '.join(want['locations'])}"
    checks.run("library still exists", library_kept, bool(logged_in))

    def new_user() -> str:
        name = f"woow-upgrade-new-{secrets.token_hex(4)}"
        made = jf.call("POST", "/Users/New", {"Name": name, "Password": secrets.token_urlsafe(18)})
        assert isinstance(made, dict) and made.get("Id"), f"created user is {made!r}"[:300]
        jf.call("DELETE", f"/Users/{made['Id']}", want=(200, 204))
        assert not [u for u in jf.users() if u.get("Name") == name], f"{name} is still listed after DELETE"
        return f"user {name} created and deleted"
    checks.run("new user can be created", new_user, bool(logged_in))
    return checks.finish("verify")


def main(hook: str) -> None:
    sys.exit({"seed": seed, "verify": verify}[hook]())
